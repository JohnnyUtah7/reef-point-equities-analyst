// Run on CI against generated synthetic data, never a live investment recommendation.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('file://'+path.resolve('examples/docs/demo-reef-point-live.html'));
  await page.waitForFunction(()=>document.getElementById('case-cover').textContent.includes('$'));
  const published=await page.locator('#published').textContent();
  assert.equal(published,'HOLD · $24');
  const bull=await page.locator('#draft-price').textContent();
  await page.locator('#reset').click();
  assert.notEqual(await page.locator('#draft-price').textContent(),bull);
  await page.locator('#knob-margin_delta').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('#published').textContent(),published);
  await page.locator('#tabs [data-view="financials"]').click();
  assert.ok((await page.locator('#fundamentals-table').textContent()).includes('cash_m'));
  await page.locator('#tabs [data-view="model"]').click();
  assert.equal(await page.locator('#sensitivity td').count(),25);
  await page.locator('#tabs [data-view="valuation"]').click();
  await page.locator('#valuation-tabs [data-view="comps-panel"]').click();
  await page.locator('#comp-metric').selectOption('pe');
  assert.ok((await page.locator('#comps-result').textContent()).includes('median'));
  await page.locator('#reset').click();
  assert.equal(await page.locator('#comp-metric').inputValue(),'ev_sales');
  await page.locator('#tabs [data-view="overview"]').click();
  fs.mkdirSync('browser-artifacts',{recursive:true});
  await page.screenshot({path:'browser-artifacts/desktop.png',fullPage:true});
  await page.locator('#theme').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.screenshot({path:'browser-artifacts/dark.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.locator('#open-rail').click();
  assert.ok((await page.locator('#rail').getAttribute('class')).includes('open'));
  await page.locator('#close-rail').click();
  await page.screenshot({path:'browser-artifacts/mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Desktop, mobile, tabs, scenario controls, published fidelity and console checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
